import math
def Arect(l,b):
    return l*b
def Asqr(l):
    return l*l
def Atri(b,h):
    return 0.5*b*h
def Acircle(r):
    return math.pi * math.pow(r,2)
def Prect(l,b):
    return 2*(l+b)
def Psqr(l):
    return 4 * l
def Ptri(a,b,c):
    return sum(a,b,c)
def circumcircle(r):
    return 2*math.pi*r
